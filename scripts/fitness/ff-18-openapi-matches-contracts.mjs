#!/usr/bin/env node
/**
 * FF-18 — OpenAPI matches the contracts.
 * fitness-functions.md FF-18 · ADR-0004 · ADR-0032 · api-contracts.md §1, §1.1
 *
 * "Regenerate docs/api/openapi.yaml from packages/contracts in CI and
 *  `git diff --exit-code` it. Fails when the committed spec differs from the
 *  generated one."
 *
 * Three checks, all blocking:
 *   1. generate-and-diff       — the committed document matches regeneration (AC-2)
 *   2. specification validity  — the document is well-formed OpenAPI (AC-3)
 *   3. api-contracts.md §1     — base path, pagination shape, problem responses,
 *                                no tenantId on a client-facing route,
 *                                and every stable error code enumerated (AC-3, AC-4)
 *
 * Usage: node scripts/fitness/ff-18-openapi-matches-contracts.mjs [--write]
 */

import { readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SPEC_PATH = join(ROOT, 'docs', 'api', 'openapi.yaml');
const REL_SPEC = 'docs/api/openapi.yaml';

const failures = [];

// ── Regenerate through the same entry point developers use ──────────────────
const generated = spawnSync(
  join(ROOT, 'node_modules', '.bin', 'tsx'),
  [join(ROOT, 'apps', 'api', 'src', 'openapi', 'render.ts')],
  { cwd: ROOT, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
);

if (generated.status !== 0) {
  console.error('FF-18 FAIL — the OpenAPI document could not be generated.\n');
  console.error(generated.stderr || generated.stdout);
  process.exit(1);
}

const regenerated = generated.stdout;

// ── 1. Generate-and-diff (AC-2, AC-6) ───────────────────────────────────────
if (!existsSync(SPEC_PATH)) {
  failures.push({
    check: 'generate-and-diff',
    message: `${REL_SPEC} is not committed. Run \`pnpm openapi:generate\`.`,
  });
} else {
  const committed = readFileSync(SPEC_PATH, 'utf8');
  if (committed !== regenerated) {
    const changed = describeDrift(committed, regenerated);
    failures.push({
      check: 'generate-and-diff',
      message:
        `${REL_SPEC} differs from the document generated by the code.\n` +
        `      Run \`pnpm openapi:generate\` and commit the result.`,
      details: changed,
    });
  }
}

/** Name the changed paths and schema components, as AC-2 requires. */
function describeDrift(committed, fresh) {
  const parse = (text) => {
    const paths = new Map();
    const schemas = new Map();
    let section = null;
    let current = null;
    for (const line of text.split('\n')) {
      if (/^paths:/.test(line)) section = 'paths';
      else if (/^\s{2}schemas:/.test(line)) section = 'schemas';
      else if (/^[a-z]/.test(line)) section = null;

      const pathMatch = line.match(/^ {2}(\/[^:]*):\s*$/);
      if (section === 'paths' && pathMatch) current = pathMatch[1];
      const schemaMatch = line.match(/^ {4}([A-Z]\w*):\s*$/);
      if (section === 'schemas' && schemaMatch) current = schemaMatch[1];

      if (current && section === 'paths') paths.set(current, (paths.get(current) ?? '') + line);
      if (current && section === 'schemas') schemas.set(current, (schemas.get(current) ?? '') + line);
    }
    return { paths, schemas };
  };

  const a = parse(committed);
  const b = parse(fresh);
  const out = [];

  for (const kind of ['paths', 'schemas']) {
    const keys = new Set([...a[kind].keys(), ...b[kind].keys()]);
    for (const key of [...keys].sort()) {
      const before = a[kind].get(key);
      const after = b[kind].get(key);
      if (before === after) continue;
      if (before === undefined) out.push(`${kind}: ${key} — added by the code, absent from the committed spec`);
      else if (after === undefined) out.push(`${kind}: ${key} — present in the committed spec, no longer produced`);
      else out.push(`${kind}: ${key} — changed`);
    }
  }
  return out.length > 0 ? out : ['(whole-document difference; run the generator to see it)'];
}

// ── 2 & 3. Validity and api-contracts.md §1 conventions ─────────────────────
const spec = existsSync(SPEC_PATH) ? readFileSync(SPEC_PATH, 'utf8') : regenerated;

let document = null;
try {
  const { parse: parseYaml } = await import('yaml');
  document = parseYaml(spec);
} catch (error) {
  failures.push({ check: 'valid-openapi', message: `document is not parseable YAML: ${error}` });
}

if (document) {
  if (!/^3\.\d+\.\d+$/.test(document.openapi ?? '')) {
    failures.push({ check: 'valid-openapi', message: `missing or malformed openapi version` });
  }
  if (!document.info?.title || !document.info?.version) {
    failures.push({ check: 'valid-openapi', message: 'info.title and info.version are required' });
  }
  if (!document.paths || Object.keys(document.paths).length === 0) {
    failures.push({ check: 'valid-openapi', message: 'the document declares no path' });
  }

  const paths = Object.keys(document.paths ?? {});

  // api-contracts.md §1 — "Base | /api/v1"
  for (const path of paths) {
    if (!path.startsWith('/api/v1')) {
      failures.push({
        check: 'base-path',
        message: `"${path}" is not under /api/v1 (api-contracts.md §1)`,
      });
    }
  }

  // api-contracts.md §1 — no client-facing route accepts tenantId (T-04, ADR-0032)
  for (const [path, operations] of Object.entries(document.paths ?? {})) {
    if (isInternalRoute(path)) continue;
    if (/\{tenantId\}/i.test(path)) {
      failures.push({
        check: 'no-tenant-id',
        message: `"${path}" declares a tenantId path parameter (api-contracts.md §1)`,
      });
    }
    for (const [method, operation] of Object.entries(operations ?? {})) {
      if (typeof operation !== 'object' || operation === null) continue;
      for (const parameter of operation.parameters ?? []) {
        if (/^tenantid$/i.test(parameter?.name ?? '')) {
          failures.push({
            check: 'no-tenant-id',
            message: `${method.toUpperCase()} "${path}" accepts a tenantId ${parameter.in} parameter (api-contracts.md §1)`,
          });
        }
      }
      const body = operation.requestBody?.content ?? {};
      for (const media of Object.values(body)) {
        for (const property of Object.keys(media?.schema?.properties ?? {})) {
          if (/^tenantid$/i.test(property)) {
            failures.push({
              check: 'no-tenant-id',
              message: `${method.toUpperCase()} "${path}" accepts tenantId in its body (api-contracts.md §1)`,
            });
          }
        }
      }
    }
  }

  // api-contracts.md §1 — errors are RFC 9457 problem+json
  const problem = document.components?.schemas?.ProblemDetails;
  if (!problem) {
    failures.push({
      check: 'problem-details',
      message: 'components.schemas.ProblemDetails is absent (api-contracts.md §1)',
    });
  } else {
    // AC-4 — every stable error code declared by packages/contracts is an
    // enumerated value. The codes are read out of the contracts source rather
    // than imported: this is a .mjs tool and the declaration is TypeScript.
    const enumerated = problem.properties?.code?.enum ?? [];
    const declared = codesFromContracts();

    for (const code of declared) {
      if (!enumerated.includes(code)) {
        failures.push({
          check: 'error-code-enum',
          message: `stable code "${code}" is missing from the problem-details enum (AC-4)`,
        });
      }
    }
    for (const code of enumerated) {
      if (!declared.includes(code)) {
        failures.push({
          check: 'error-code-enum',
          message: `"${code}" is enumerated in the spec but is not a stable code (api-contracts.md §1.1)`,
        });
      }
    }

    // Close the triangle: the architecture document is the authority for the
    // set, so a code added there and nowhere else must also fail the gate.
    const fromDocument = codesFromArchitecture();
    for (const code of fromDocument) {
      if (!declared.includes(code)) {
        failures.push({
          check: 'error-code-enum',
          message: `"${code}" is declared in api-contracts.md §1.1 but not in packages/contracts`,
        });
      }
    }
    for (const code of declared) {
      if (!fromDocument.includes(code)) {
        failures.push({
          check: 'error-code-enum',
          message: `"${code}" is declared in packages/contracts but not in api-contracts.md §1.1`,
        });
      }
    }
  }

  // api-contracts.md §1 — cursor pagination, never offset.
  for (const [path, operations] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(operations ?? {})) {
      if (typeof operation !== 'object' || operation === null) continue;
      for (const parameter of operation.parameters ?? []) {
        if (/^offset$/i.test(parameter?.name ?? '')) {
          failures.push({
            check: 'cursor-pagination',
            message: `${method.toUpperCase()} "${path}" offers offset pagination (ADR-0032 rejects it)`,
          });
        }
      }
    }
  }
}

/** Internal/Studio routes may accept an explicit tenantId (api-contracts.md §4). */
function isInternalRoute(path) {
  return /^\/api\/v1\/(internal|control|admin)\b/.test(path);
}

/**
 * The stable set as declared by api-contracts.md §1.1 — the authority.
 *
 * Only the first paragraph after the heading is the list; prose that follows
 * may mention individual codes.
 */
function codesFromArchitecture() {
  const doc = readFileSync(join(ROOT, 'docs/architecture/api-contracts.md'), 'utf8');
  const start = doc.indexOf('### 1.1 Error codes');
  const afterHeading = doc.indexOf('\n', start) + 1;
  const section = doc.slice(afterHeading, doc.indexOf('## 2.', afterHeading));
  const paragraph = section
    .split(/\n\s*\n/)
    .map((block) => block.trim())
    .find((block) => block.length > 0);
  const codes = [...(paragraph ?? '').matchAll(/`([a-z_]+)`/g)].map((m) => m[1]);
  if (codes.length < 10) {
    throw new Error(`api-contracts.md §1.1 parser extracted only ${codes.length} code(s)`);
  }
  return codes;
}

/**
 * The stable set as declared by packages/contracts — the single declaration
 * site (P1.04 AC-2).
 */
function codesFromContracts() {
  const source = readFileSync(
    join(ROOT, 'packages/contracts/src/errors/error-codes.ts'),
    'utf8',
  );
  const block = source.slice(
    source.indexOf('export const ERROR_CODES'),
    source.indexOf('] as const;'),
  );
  return [...block.matchAll(/'([a-z_]+)'/g)].map((m) => m[1]);
}

// ── Report ──────────────────────────────────────────────────────────────────
const pathCount = document?.paths ? Object.keys(document.paths).length : 0;
const schemaCount = document?.components?.schemas
  ? Object.keys(document.components.schemas).length
  : 0;

console.log(`FF-18  paths=${pathCount}  schemas=${schemaCount}  failures=${failures.length}`);

if (failures.length === 0) {
  console.log('FF-18 PASS — the published OpenAPI document matches the contracts.');
  process.exit(0);
}

console.error('\nFF-18 FAIL — the published contract and the code disagree.\n');
for (const failure of failures) {
  console.error(`  [${failure.check}] ${failure.message}`);
  for (const detail of failure.details ?? []) console.error(`      - ${detail}`);
}
console.error('');
process.exit(1);
